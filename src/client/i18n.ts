const TABLES: Record<Lang, Partial> = { en, it, es, fr, pt };

let current: Lang = 'en';

export function detectLang(): Lang {
  const nav = (globalThis.navigator?.language ?? 'en').slice(0, 2).toLowerCase();
  return (LANGS as readonly string[]).includes(nav) ? (nav as Lang) : 'en';
}

export function setLang(l: Lang) {
  current = l;
  document.documentElement.lang = l;
}

export const getLang = () => current;

type StringKey = { [K in keyof Strings]: Strings[K] extends string ? K : never }[keyof Strings];

export function t(key: StringKey, vars?: Record<string, string | number>): string {
  let s = (TABLES[current][key] ?? en[key]) as string;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export const rulesText = (): string[] => TABLES[current].rules ?? en.rules;
